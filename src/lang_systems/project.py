"""Project scaffolding for ``qtr new`` and ``qtr init``."""

from __future__ import annotations

from pathlib import Path
import json
import re
import tomllib

Source = str | Path

_MANIFEST_NAME = "pyproject.toml"
_ENTRY_RELATIVE_PATH = Path("src") / "main.qtr"
_README_NAME = "README.md"
_TESTS_DIR = Path("tests")
_GITIGNORE_NAME = ".gitignore"
_VALID_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")

_MAIN_SOURCE = '''"""Generated by qtr new."""

def main() -> None:
    print("Hello from Quantar!")

if __name__ == "__main__":
    main()
'''

_TEST_SOURCE = "assert True\n"

_GITIGNORE = """build/
dist/
quantar_compile/
__pycache__/
*.spec
"""


def _readme(name: str) -> str:
    """Return starter README text for ``name``."""
    return (
        f"# {name}\n\n"
        "Generated by `qtr new` / `qtr init`.\n\n"
        "```bash\n"
        "qtr run\n"
        "qtr check\n"
        "qtr compile\n"
        "```\n"
    )


def _quantar_section(entry: str, rust: bool) -> str:
    """Return the ``[tool.quantar]`` settings table."""
    return (
        "[tool.quantar]\n"
        f'entry = "{entry}"\n'
        'output = "src/main.py"\n'
        'compile-to = "py"\n'
        'mode = "standalone"\n'
        f'rust = {"true" if rust else "false"}\n'
        "jobs = 2\n"
    )


def _manifest(name: str, rust: bool) -> str:
    """Return a minimal ``pyproject.toml`` with Quantar settings."""
    quoted_name = json.dumps(name)
    entry = _ENTRY_RELATIVE_PATH.as_posix()
    return (
        "[build-system]\n"
        'requires = ["hatchling"]\n'
        'build-backend = "hatchling.build"\n'
        "\n"
        "[project]\n"
        f"name = {quoted_name}\n"
        'version = "0.1.0"\n'
        'description = "A Quantar project"\n'
        'requires-python = ">=3.12"\n'
        'dependencies = ["quantar"]\n'
        "\n"
        + _quantar_section(entry, rust)
    )


def _write_manifest(root: Path, name: str, rust: bool, created: list[Path]) -> None:
    """Write or extend ``pyproject.toml`` without clobbering user settings."""
    path = root / _MANIFEST_NAME
    if not path.exists():
        path.write_text(_manifest(name, rust), encoding="utf-8")
        created.append(path)
        return

    text = path.read_text(encoding="utf-8")
    try:
        document = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise ValueError(f"Invalid TOML in {path}: {error}") from error

    tool = document.get("tool")
    if isinstance(tool, dict) and isinstance(tool.get("quantar"), dict):
        return

    section = "\n" + _quantar_section(_ENTRY_RELATIVE_PATH.as_posix(), rust)
    path.write_text(text.rstrip() + "\n" + section, encoding="utf-8")
    created.append(path)


def _validate_name(name: str) -> None:
    """Reject names that cannot be used as a project directory name."""
    if not _VALID_NAME.fullmatch(name):
        raise ValueError(f"Invalid project name {name!r}; use letters, digits, '_' or '-' and start with a letter or '_'")


def _write_if_missing(root: Path, relative: Path, text: str, created: list[Path]) -> None:
    """Write a scaffold file unless the user already has one there."""
    path = root / relative
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    created.append(path)


def _scaffold(root: Path, name: str, rust: bool) -> tuple[Path, list[Path]]:
    """Create missing project files and return the root and created files."""
    root.mkdir(parents=True, exist_ok=True)
    created: list[Path] = []
    _write_manifest(root, name, rust, created)
    _write_if_missing(root, _ENTRY_RELATIVE_PATH, _MAIN_SOURCE, created)
    _write_if_missing(root, Path(_README_NAME), _readme(name), created)
    package_name = name.replace("-", "_")
    _write_if_missing(root, _TESTS_DIR / f"test_{package_name}.qtr", _TEST_SOURCE, created)
    _write_if_missing(root, Path(_GITIGNORE_NAME), _GITIGNORE, created)
    return root, created


def new_project(name: str, parent: Source | None = None, *, rust: bool = False) -> Path:
    """Create a new Quantar project directory named ``name``."""
    _validate_name(name)
    destination = Path(parent).resolve() if parent is not None else Path.cwd().resolve()
    root = destination / name
    if root.exists() and any(root.iterdir()):
        raise FileExistsError(f"Project directory is not empty: {root}")
    created_root, _ = _scaffold(root, name, rust)
    return created_root


def init_project(root: Source | None = None, name: str | None = None, *, rust: bool = False) -> Path:
    """Initialize a Quantar project in an existing directory."""
    target = Path(root).resolve() if root is not None else Path.cwd().resolve()
    project_name = name or target.name
    _validate_name(project_name)
    created_root, _ = _scaffold(target, project_name, rust)
    return created_root


__all__ = ["init_project", "new_project"]
